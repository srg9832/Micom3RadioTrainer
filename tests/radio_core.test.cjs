const assert = require('node:assert/strict');
const radio = require('../static/radio_core.js');

assert.equal(radio.MAX_CHANNEL, 200);
assert.equal(radio.parseFrequency('14,000.00'), 14000000);
assert.equal(radio.parseFrequency('14002.50'), 14002500);
assert.equal(radio.parseFrequency('100.00'), 100000);
assert.equal(radio.parseFrequency('14,000.001'), null);
assert.equal(radio.parseFrequency('99999'), null);
assert.equal(radio.parseFrequency(''), null);
assert.equal(radio.formatFrequency(14002500), '14,002.50');
assert.equal(radio.validTransmit(1500000), false);
assert.equal(radio.validReceive(1500000), true);
assert.deepEqual(radio.makeTuning('SMPX', 14000000, 14000000), {type:'SMPX',rxHz:14000000,txHz:14000000});
assert.deepEqual(radio.makeTuning('RXO', 14000000, 14000000), {type:'RXO',rxHz:14000000,txHz:null});
assert.deepEqual(radio.makeTuning('TXO', 14000000, 14000000), {type:'TXO',rxHz:null,txHz:14000000});
assert.equal(radio.makeTuning('TXO', 14000000, 1400000), null);
const rx = {rxHz:14000000, txHz:null, band:'USB', mode:'SSB'};
const tx = {rxHz:null, txHz:14000000, band:'USB', mode:'SSB'};
assert.equal(radio.canReceive(rx, tx), true);
assert.equal(radio.canReceive(tx, rx), false);
assert.equal(radio.canConnect(rx, tx), true);
assert.equal(radio.canConnect(rx, {...tx, band:'LSB'}), false);
assert.equal(radio.canConnect(rx, {...tx, mode:'AME'}), false);
assert.equal(radio.canConnect(rx, {...tx, txHz:14002500}), false);
assert.equal(radio.canConnect({rxHz:null,txHz:null,band:'USB',mode:'SSB'}, {...tx,txHz:null}), false);
assert.deepEqual(radio.nextProgrammedChannel(4, 1, {1:'x',2:'y',4:'z'}),1);
assert.deepEqual(radio.nextProgrammedChannel(1,-1,{1:'x',2:'y',4:'z'}),4);
assert.equal(radio.nextProgrammedChannel(1,1,{}),null);
assert.equal(radio.normalizedRemote({frequency:'14,000.00',band:'USB',mode:'SSB'}).rxHz,14000000);
assert.equal(radio.normalizedRemote({rx_frequency:null,tx_frequency:14000000,frequency:'14,000.00'}).rxHz,null);
assert.equal(radio.normalizedRemote({rx_frequency:null,tx_frequency:null,frequency:'14,000.00'}).rxHz,14000000);
console.log('radio_core tests passed');
